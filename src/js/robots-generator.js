// robots-generator.js - Interactive Robots.txt File Generator
(function () {
  'use strict';

  function init() {
    const defaultPolicy = document.getElementById('robDefaultPolicy');
    const crawlDelayInp = document.getElementById('robCrawlDelay');
    const sitemapInp = document.getElementById('robSitemap');

    // Bot checkboxes
    const googleBot = document.getElementById('robGoogle');
    const bingBot = document.getElementById('robBing');
    const baiduBot = document.getElementById('robBaidu');
    const yandexBot = document.getElementById('robYandex');

    const pathInp = document.getElementById('robNewPath');
    const addPathBtn = document.getElementById('robAddPathBtn');
    const pathsList = document.getElementById('robPathsList');

    const outputEl = document.getElementById('robOutput');
    const copyBtn = document.getElementById('robCopyBtn');
    const dlBtn = document.getElementById('robDlBtn');

    if (!outputEl) return;

    let disallowPaths = ['/admin/', '/private/', '/tmp/'];

    function renderPaths() {
      if (!pathsList) return;
      pathsList.innerHTML = '';
      disallowPaths.forEach((path, idx) => {
        const span = document.createElement('span');
        span.style.cssText = 'display:inline-flex;align-items:center;background:var(--card);border:1px solid var(--border);padding:3px 8px;border-radius:12px;font-size:0.8rem;margin:3px;font-family:monospace;';
        span.innerHTML = `Disallow: ${path} <button type="button" style="background:none;border:none;color:var(--bad,#ef4444);cursor:pointer;margin-left:6px;" data-idx="${idx}">✕</button>`;
        span.querySelector('button').addEventListener('click', () => {
          disallowPaths.splice(idx, 1);
          renderPaths();
          generate();
        });
        pathsList.appendChild(span);
      });
    }

    function generate() {
      const isAllowAll = defaultPolicy ? defaultPolicy.value === 'allow' : true;
      const delay = (crawlDelayInp && crawlDelayInp.value) ? parseInt(crawlDelayInp.value, 10) : null;
      const sitemap = (sitemapInp && sitemapInp.value.trim()) || '';

      let txt = '# Robots.txt generated by Toolswick SEO Tools\n';
      txt += '# Learn more: https://www.robotstxt.org/\n\n';

      // Default wildcard section
      txt += 'User-agent: *\n';
      if (!isAllowAll) {
        txt += 'Disallow: /\n';
      } else {
        if (disallowPaths.length === 0) {
          txt += 'Disallow:\n';
        } else {
          disallowPaths.forEach(p => {
            txt += `Disallow: ${p}\n`;
          });
        }
      }

      if (delay && delay > 0) {
        txt += `Crawl-delay: ${delay}\n`;
      }
      txt += '\n';

      // Specific bots if custom rules selected
      function appendBot(name, el) {
        if (el && el.value === 'disallow') {
          txt += `User-agent: ${name}\nDisallow: /\n\n`;
        }
      }

      appendBot('Googlebot', googleBot);
      appendBot('Bingbot', bingBot);
      appendBot('Baiduspider', baiduBot);
      appendBot('Yandex', yandexBot);

      if (sitemap) {
        txt += `Sitemap: ${sitemap}\n`;
      }

      outputEl.value = txt.trim() + '\n';
    }

    if (addPathBtn && pathInp) {
      addPathBtn.addEventListener('click', () => {
        let p = pathInp.value.trim();
        if (p) {
          if (!p.startsWith('/')) p = '/' + p;
          if (!disallowPaths.includes(p)) {
            disallowPaths.push(p);
            pathInp.value = '';
            renderPaths();
            generate();
          }
        }
      });
      pathInp.addEventListener('keydown', e => {
        if (e.key === 'Enter') {
          e.preventDefault();
          addPathBtn.click();
        }
      });
    }

    [defaultPolicy, crawlDelayInp, sitemapInp, googleBot, bingBot, baiduBot, yandexBot].forEach(inp => {
      if (inp) inp.addEventListener('change', generate);
      if (inp) inp.addEventListener('input', generate);
    });

    if (copyBtn) {
      copyBtn.addEventListener('click', () => {
        navigator.clipboard.writeText(outputEl.value).then(() => {
          if (window.TK && TK.toast) TK.toast('Robots.txt copied to clipboard!', 'success');
        });
      });
    }

    if (dlBtn) {
      dlBtn.addEventListener('click', () => {
        const blob = new Blob([outputEl.value], { type: 'text/plain;charset=utf-8;' });
        const a = document.createElement('a');
        a.href = URL.createObjectURL(blob);
        a.download = 'robots.txt';
        a.click();
      });
    }

    renderPaths();
    generate();
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
